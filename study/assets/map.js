/* The concept map.

   Layout is deliberate rather than force-directed: x is position in the book,
   y is position within the chapter. A spring layout of 172 nodes is a hairball
   and tells you nothing; laying reading order along x means every dependency
   edge visibly points BACKWARD, and the shape of the book — everything leaning
   back onto Foundations — is the first thing you see.

   Data comes from assets/mapdata.js, generated by build_map(). */
(function () {
  'use strict';
  var PART_COLOR = { 'I': '--accent', 'II': '--blue', 'III': '--purple', 'IV': '--green' };

  document.addEventListener('DOMContentLoaded', function () {
    var cv = document.getElementById('conceptmap');
    var data = window.MAP;
    if (!cv || !data || !data.nodes.length) return;
    var cx = null;
    try { cx = cv.getContext('2d'); } catch (e) { }
    if (!cx) return;

    var foot = document.getElementById('mapfoot');
    var reset = document.getElementById('map-reset');
    var N = data.nodes, E = data.edges;
    var W = 0, H = 0, panX = 0, panY = 0, drag = false, lx = 0, ly = 0;
    var hot = -1, pin = -1;

    function css(v) {
      return getComputedStyle(document.documentElement).getPropertyValue(v).trim();
    }
    function colorOf(n) { return css(PART_COLOR[n.part] || '--ink-faint'); }

    /* --- layout: x = reading order, y = spread within the chapter --- */
    var chapters = {};
    N.forEach(function (n, i) { (chapters[n.ch] = chapters[n.ch] || []).push(i); });
    var chapterList = Object.keys(chapters).map(Number).sort(function (a, b) { return a - b; });
    var maxCh = chapterList[chapterList.length - 1] || 1;
    N.forEach(function (n) {
      var members = chapters[n.ch];
      n._k = members.indexOf(N.indexOf(n));
      n._of = members.length;
    });
    /* indexOf on objects is O(n²) for 172 — do it once, by index instead */
    chapterList.forEach(function (ch) {
      chapters[ch].forEach(function (idx, k) { N[idx]._k = k; N[idx]._of = chapters[ch].length; });
    });

    function pos(n) {
      var padX = 46, padY = 34;
      var x = padX + ((n.ch - 1) / Math.max(1, maxCh - 1)) * (W - padX * 2);
      /* stagger alternate columns so dense chapters do not overlap */
      var span = H - padY * 2;
      var y = padY + (n._of === 1 ? span / 2 : (n._k / (n._of - 1)) * span);
      var wob = (n.ch % 2 ? 1 : -1) * (n._k % 2 ? 7 : -7);
      return { x: x + panX + wob, y: y + panY, r: 2.6 + Math.min(n.d, 12) * 0.62 };
    }

    function neighbours(i) {
      var up = {}, down = {};
      E.forEach(function (e) {
        if (e[0] === i) up[e[1]] = 1;      // i leans on e[1]
        if (e[1] === i) down[e[0]] = 1;    // e[0] leans on i
      });
      return { up: up, down: down };
    }

    function draw() {
      if (!W || !H) return;
      cx.clearRect(0, 0, W, H);
      var sel = pin >= 0 ? pin : hot;
      var nb = sel >= 0 ? neighbours(sel) : null;

      /* chapter guides */
      cx.strokeStyle = css('--line-soft'); cx.lineWidth = 1;
      chapterList.forEach(function (ch) {
        var x = 46 + ((ch - 1) / Math.max(1, maxCh - 1)) * (W - 92) + panX;
        cx.globalAlpha = .55;
        cx.beginPath(); cx.moveTo(x, 18); cx.lineTo(x, H - 14); cx.stroke();
        cx.globalAlpha = 1;
        cx.fillStyle = css('--ink-faint');
        cx.font = '700 9.5px system-ui, sans-serif';
        cx.textAlign = 'center';
        cx.fillText('CH ' + ch, x, 12);
      });
      cx.textAlign = 'left';

      E.forEach(function (e) {
        var a = pos(N[e[0]]), b = pos(N[e[1]]);
        var on = sel >= 0 && (e[0] === sel || e[1] === sel);
        cx.strokeStyle = on ? colorOf(N[sel]) : css('--line');
        cx.globalAlpha = sel >= 0 ? (on ? .9 : .07) : .30;
        cx.lineWidth = on ? 1.6 : .8;
        var mx = (a.x + b.x) / 2, my = (a.y + b.y) / 2;
        cx.beginPath(); cx.moveTo(a.x, a.y);
        cx.quadraticCurveTo(mx, my - Math.abs(a.x - b.x) * 0.14, b.x, b.y);
        cx.stroke();
      });
      cx.globalAlpha = 1;

      N.forEach(function (n, i) {
        var p = pos(n), on = i === sel, near = nb && (nb.up[i] || nb.down[i]);
        cx.globalAlpha = sel >= 0 ? (on || near ? 1 : .22) : 1;
        cx.beginPath(); cx.arc(p.x, p.y, p.r + (on ? 2.2 : 0), 0, 7);
        cx.fillStyle = colorOf(n); cx.fill();
        if (on) { cx.strokeStyle = css('--bg'); cx.lineWidth = 1.8; cx.stroke(); }
      });
      cx.globalAlpha = 1;

      if (sel >= 0) {
        var p = pos(N[sel]), label = '§ ' + N[sel].sec + '  ' + N[sel].t;
        cx.font = '600 11.5px system-ui, sans-serif';
        var w = cx.measureText(label).width;
        var bx = Math.max(6, Math.min(W - w - 16, p.x - w / 2 - 6)), by = p.y - p.r - 24;
        if (by < 4) by = p.y + p.r + 6;
        cx.fillStyle = css('--bg-panel'); cx.strokeStyle = css('--line'); cx.lineWidth = 1;
        cx.beginPath(); cx.roundRect(bx, by, w + 12, 20, 5); cx.fill(); cx.stroke();
        cx.fillStyle = css('--ink'); cx.fillText(label, bx + 6, by + 14);
      }
    }

    function size() {
      var d = window.devicePixelRatio || 1;
      W = cv.clientWidth; H = cv.clientHeight;
      if (!W || !H) return;
      cv.width = W * d; cv.height = H * d; cx.setTransform(d, 0, 0, d, 0, 0);
      draw();
    }

    function pick(mx, my) {
      var best = -1, bd = 13;
      N.forEach(function (n, i) {
        var p = pos(n), dd = Math.hypot(p.x - mx, p.y - my);
        if (dd < bd + p.r) { bd = dd; best = i; }
      });
      return best;
    }

    function say(i) {
      if (i < 0) {
        foot.innerHTML = 'Reading order runs left to right. Bigger dots are leaned on by more ' +
          'lessons — those are the ones worth over-learning.';
        return;
      }
      var n = N[i], nb = neighbours(i);
      var up = Object.keys(nb.up).length, down = Object.keys(nb.down).length;
      foot.innerHTML =
        '<b>§ ' + n.sec + ' · ' + n.t + '</b> &nbsp;·&nbsp; leans on <b>' + up + '</b>, ' +
        'leaned on by <b>' + down + '</b> &nbsp;·&nbsp; ' +
        '<a href="' + n.f + '">open the lesson →</a>' +
        (pin === i ? ' &nbsp;·&nbsp; <i>pinned — click it again to release</i>' : '');
    }

    cv.addEventListener('pointermove', function (e) {
      var r = cv.getBoundingClientRect(), mx = e.clientX - r.left, my = e.clientY - r.top;
      if (drag) { panX += mx - lx; panY += my - ly; lx = mx; ly = my; draw(); return; }
      var h = pick(mx, my);
      if (h !== hot) {
        hot = h; cv.style.cursor = h >= 0 ? 'pointer' : 'grab';
        if (pin < 0) say(h);
        draw();
      }
    });
    cv.addEventListener('pointerdown', function (e) {
      var r = cv.getBoundingClientRect(), mx = e.clientX - r.left, my = e.clientY - r.top;
      var h = pick(mx, my);
      if (h >= 0) { pin = (pin === h ? -1 : h); say(pin >= 0 ? pin : h); draw(); }
      else { drag = true; lx = mx; ly = my; cv.style.cursor = 'grabbing'; cv.setPointerCapture(e.pointerId); }
    });
    cv.addEventListener('pointerup', function (e) {
      drag = false; cv.style.cursor = 'grab';
      try { cv.releasePointerCapture(e.pointerId); } catch (x) { }
    });
    cv.addEventListener('pointerleave', function () { if (pin < 0) { hot = -1; say(-1); draw(); } });
    if (reset) reset.addEventListener('click', function () {
      panX = panY = 0; pin = hot = -1; say(-1); draw();
    });
    window.addEventListener('resize', size);
    window.addEventListener('themechange', draw);

    /* --- the load-bearing list, counted from the same graph --- */
    var ol = document.getElementById('loadbearing');
    if (ol) {
      N.map(function (n, i) { return { n: n, i: i }; })
        .sort(function (a, b) { return b.n.d - a.n.d; })
        .slice(0, 10)
        .forEach(function (x) {
          var li = document.createElement('li');
          li.innerHTML = '<a href="' + x.n.f + '">§ ' + x.n.sec + ' · ' + x.n.t + '</a>' +
            '<span class="lb-n">' + x.n.d + ' lessons lean on it</span>';
          ol.appendChild(li);
        });
    }

    size(); say(-1);
  });
})();
